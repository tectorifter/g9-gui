-- WHY THIS CATALOG IS DIFFERENT FROM THE OTHERS.  The other catalogs in this
-- folder are generated from PokeAPI, whose name tables carry an official (or
-- major) localization for every language this suite ships.  PokeAPI has NO
-- such table for Brazilian Portuguese: the main-series games were never
-- localized into pt-BR, so its move_names / item_names / pokemon_species_names
-- CSVs have ZERO pt-BR rows and ability_names has only twelve.  The one
-- OFFICIAL Brazilian Portuguese Pokemon localization that exists is Pokemon
-- GO (Niantic / The Pokemon Company International), and its text dump is the
-- backbone of this file.  Everything else is the suite's own Brazilian
-- Portuguese, following the terminology the Brazilian community actually uses
-- (many names are direct cognates: Adaptability -> Adaptabilidade,
-- Intimidate -> Intimidacao).
--
-- The name tables:
--   species    The sixteen species whose OFFICIAL pt-BR name differs from the
--              international one -- the Paradox Pokemon, Type: Null and
--              Sirfetch'd (whose pt-BR spelling uses the typographic
--              apostrophe).  Every other species keeps its international name,
--              exactly as the three Brazilian mods do: none of them ships a
--              species-name table, because Brazil uses the international
--              names.  Keyed by NATIONAL DEX number.
--   moves      Keyed by the FOLDED English name (ui/translation.lua's fold:
--   items/     lowercase, then the spaces and punctuation the engine drops).
--   abilities  Pokemon GO's official pt-BR name wins wherever GO carries the
--              move or item; where it does not, the suite's own Brazilian
--              name is used.  Only entries whose name actually DIFFERS from
--              the English source are listed -- a record the translation mod
--              already renamed never folds to an English key, so it is left
--              exactly as the mod rendered it.
--
-- The tables that DO the suite's own work are unchanged: `ui` (footer hints,
-- header readouts, START captions, PC/dex furniture), `messages` /
-- `messageTemplates` (the battle scene's refusals and outcome lines, the
-- trade pages) and `engineLearner` (the eight Gen 1 learner literals a Gold/
-- Crystal boot falls back to).  Those keys are the English source string,
-- byte-for-byte; the runtime's fold is not used for `ui`.
--
-- BUILD NOTES.  The species/move/item names were extracted from the Pokemon
-- GO Brazilian Portuguese text dump (PokeMiners/pogo_assets, "Texts/Latest
-- APK/Brazilian Portuguese.txt", resource keys `pokemon_name_<dex>`,
-- `move_name_<id>` and `item_*_name`), folded to the engine's keys with the
-- same fold() the runtime uses.  There is no generator script; see src/
-- README.md for the extraction recipe.
